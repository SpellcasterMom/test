#pragma once

#include <Adafruit_PWMServoDriver.h>
#include "config.h"
#include "types.h"

/**
 * Класс ServoController — управление сервоприводами через драйвер PCA9685.
 *
 * PCA9685 — это 16-канальный ШИМ-драйвер, управляемый по шине I2C.
 * Каждый канал генерирует импульсы с заданной шириной (PWM), что позволяет
 * управлять углом поворота сервопривода.
 *
 * Частота ШИМ устанавливается на 50 Гц (стандарт для сервоприводов).
 * Период полного цикла = 1 / 50 = 20 мс (20000 мкс).
 * Длительность управляющего импульса от 1 мс до 2 мс соответствует
 * углу от 0° до 180° (точные диапазоны зависят от конкретного серво).
 *
 * PCA9685 разрешает ширину импульса с точностью до 12 бит (0–4096 тиков).
 * 1 тик = 20000 мкс / 4096 ≈ 4.88 мкс.
 */
class ServoController {
public:
    /**
     * Инициализация драйвера PCA9685.
     * Устанавливает I2C-адрес 0x40 (стандартный адрес модуля),
     * вызывает begin() для настройки периферии I2C,
     * устанавливает частоту ШИМ 50 Гц и загружает конфигурации
     * сервоприводов из DEFAULT_CONFIG.
     */
    void init();

    /**
     * Установка угла для одного сервопривода.
     *
     * Алгоритм:
     * 1. Валидация servoId (0–6) и проверка флага enabled.
     * 2. Применение корректирующего множителя (correctionFactor).
     *    Множитель задаётся в процентах: 100.0 — без коррекции,
     *    >100 — усиление, <100 — ослабление хода серво.
     * 3. Инвертирование направления (isInverted).
     *    Если серво установлено «зеркально», угол меняет знак.
     * 4. Ограничение (clamping) угла допустимыми пределами
     *    [minAngle, maxAngle] — защита от механического повреждения.
     * 5. Конвертация угла в ширину ШИМ-импульса (мкс → тики).
     * 6. Запись значения PWM в соответствующий канал PCA9685.
     * 7. Сохранение текущего угла в currentAngles.
     *
     * @param servoId  индекс сервопривода (0–6)
     * @param angle    целевой угол в градусах
     */
    void setAngle(int servoId, float angle);

    /**
     * Последовательная установка углов для всех 7 сервоприводов.
     * Вызывает setAngle() для каждого индекса 0–6.
     *
     * @param angles  структура с массивом углов для всех серво
     */
    void setAngles(const JointAngles &angles);

    /**
     * Возвращает текущие запомненные углы всех сервоприводов.
     * Значения обновляются при каждом вызове setAngle().
     */
    JointAngles getCurrentAngles();

    /**
     * Загрузка новой конфигурации для 7 сервоприводов.
     * Конфигурация содержит параметры каждого серво:
     * диапазон углов, диапазон PWM, корректирующий множитель,
     * флаг инвертирования и компенсацию люфта.
     *
     * @param configs  массив из 7 элементов ServoConfig
     */
    void setConfig(const ServoConfig configs[7]);

    /**
     * Включение сервоприводов.
     * После вызова setAngle() будет выдавать ШИМ-сигнал.
     */
    void enable();

    /**
     * Отключение сервоприводов.
     * Устанавливает флаг enabled = false, после чего setAngle()
     * игнорирует все команды. Также обнуляет PWM на всех каналах,
     * что отключает подачу питания на серво (серво «разжимается»).
     */
    void disable();

private:
    /** Объект драйвера PCA9685, управляемый по I2C */
    Adafruit_PWMServoDriver pwm;

    /** Массив конфигураций для 7 сервоприводов (6 осей + захват) */
    ServoConfig configs[7];

    /** Текущие углы всех сервоприводов (обновляется при setAngle) */
    JointAngles currentAngles;

    /** Флаг включения: true — серво управляются, false — игнорируются */
    bool enabled = true;

    /**
     * Внутренний метод: конвертация угла в ширину PWM-импульса.
     *
     * Формула линейной интерполяции:
     *   pulse_us = minPWM + (angle - minAngle) * (maxPWM - minPWM) / (maxAngle - minAngle)
     *
     * где:
     *   minPWM, maxPWM — ширина импульса в микросекундах для предельных углов
     *   minAngle, maxAngle — предельные углы серво в градусах
     *
     * Результат в микросекундах преобразуется в тики PCA9685:
     *   ticks = pulse_us / (20000 / 4096) = pulse_us * 4096 / 20000
     *
     * @param servoId  индекс сервопривода
     * @param angle    угол в градусах (уже скорректированный)
     * @return         значение тиков (0–4096) для регистра PCA9685
     */
    uint16_t angleToPulse(int servoId, float angle);
};
