/*
 * gcode_parser.h — Заголовочный файл парсера G-кодов
 *
 * Универсальный таблице-ориентированный парсер G-кодов для 6-DOF роботической
 * манипуляции с сервоприводами. Поддерживает:
 *
 * 1) Табличный поиск команд — каждая команда определена в массиве COMMANDS[]
 *    с указанием имени, параметров и обработчика. Парсер последовательно
 *    перебирает записи таблицы для поиска совпадения.
 *
 * 2) Прямой ввод углов сервоприводов P1..P7 — позволяет задать угол каждого
 *    серво независимо от кинематической модели (например, P1=90 P2=45).
 *
 * 3) Универсальные параметры L, R, S, ... — любая буква от A до Z может быть
 *    использована как параметр команды. Значения хранятся в массиве params[]
 *    по индексу (letter - 'A'). Это позволяет расширять команды без изменения
 *    структуры парсера.
 *
 * 4) Стандартные параметры XYZABC, F, J — стандартные параметры позиции,
 *    ориентации, скорости подачи и состояния захвата.
 */

#pragma once

#include "types.h"

class GCodeParser {
public:
    /**
     * parse — Разбор строки G-кода и возврат структуры GCodeCommand.
     *
     * Алгоритм:
     *   1. Удаление пробелов по краям и привод к верхнему регистру.
     *   2. Извлечение имени команды (первый токен до пробела).
     *   3. Поиск имени в таблице COMMANDS[].
     *   4. Вызов parseParams() для разбора параметров команды.
     *   5. Вызов обработчика команды (handler).
     *
     * @param line — входная строка G-кода (например, "G1 X100 Y50 F500")
     * @return GCodeCommand — заполненная структура с типом, параметрами и результатом
     */
    GCodeCommand parse(String line);

private:
    /**
     * parseParams — Разбор параметров команды из строки G-кода.
     *
     * Перебирает все параметры, определённые в таблице CommandDef, и для каждого
     * извлекает числовое значение из строки. Поддерживает три типа параметров:
     *
     *   P(letter, index=-1): Прямой ввод P1..P7 — парсит "P1=90" и записывает
     *     угол в массив servoAngles для соответствующего сервопривода.
     *
     *   L/R/S: Целочисленные или специальные параметры — ищет формат "L=10"
     *     или "L 10" и записывает значение через setParamValue().
     *
     *   Все остальные (X, Y, Z, A, B, C, F, J, ...): Стандартные параметры —
     *     ищет букву в строке, опционально пропускает '=', извлекает число
     *     до следующего пробела.
     *
     * @param cmd — ссылка на структуру команды для заполнения параметрами
     * @param line — полная строка G-кода (уже в верхнем регистре)
     * @param def — определение команды из таблицы COMMANDS[]
     */
    void parseParams(GCodeCommand &cmd, String line, const CommandDef &def);

    /**
     * setParamValue — Установка значения параметра в структуре GCodeCommand.
     *
     * Маппит букву параметра на поле структуры команды:
     *   X/Y/Z -> позиция (position.x/y/z), устанавливается флаг hasPosition
     *   A/B/C -> ориентация (orientation.x/y/z), устанавливается флаг hasOrientation
     *   F     -> скорость подачи (feedrate), устанавливается флаг hasFeedrate
     *   J     -> состояние захвата (gripper), устанавливается флаг hasGripper
     *   Остальные (L, R, S, ...) -> универсальный массив params[idx] по индексу
     *     (letter - 'A'), устанавливается флаг hasParam[idx]
     *
     * @param cmd — ссылка на структуру команды
     * @param letter — буква параметра
     * @param index — индекс параметра в таблице определений (не используется
     *                для универсальных параметров)
     * @param val — числовое значение параметра
     */
    void setParamValue(GCodeCommand &cmd, char letter, int index, float val);
};
