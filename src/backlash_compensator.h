#pragma once

#include "types.h"

/**
 * Класс BacklashCompensator — компенсация люфта (backlash) сервоприводов.
 *
 * ЛЮФТ (BACKLASH) — это мёртвая зона в передаче сервопривода,
 * возникающая из-за зазоров между шестернями, тягами и редуктором.
 *
 * ПРИНЦИП РАБОТЫ КОМПЕНСАЦИИ:
 *
 * Когда сервопривод меняет направление вращения (например, с по часовой
 * стрелке на против), люфт приводит к тому, что первые несколько градусов
 * поворота «съедаются» зазором, и выходной вал не движется.
 *
 * Алгоритм компенсации:
 * 1. Отслеживается последнее направление вращения серво.
 * 2. При обнаружении смены направления к целевому углу прибавляется
 *    поправка, равная величине люфта.
 * 3. Поправка прибавляется в направлении нового движения, чтобы
 *    «протолкнуть» передачу через мёртвую зону.
 *
 * Пример:
 *   Серво двигается от 0° до 90° (направление +1, люфт = 2°).
 *   Затем команда: двигаться до 45° (направление меняется на -1).
 *   Без компенсации: серво повернёт на 45° - 2° = 43° от текущей позиции.
 *   С компенсацией: к целевому углу прибавляется -2°, серво получит
 *   команду 43° и реально пройдёт 43° + 2° = 45° от текущей позиции.
 *
 * ВАЖНО: компенсация применяется ТОЛЬКО при смене направления.
 * При движении в том же направлении поправка не нужна — люфт уже «выбран».
 */
class BacklashCompensator {
public:
    /**
     * Установка величины люфта для конкретного сервопривода.
     *
     * @param servoId  индекс сервопривода (0–6)
     * @param degrees  величина люфта в градусах (обычно 0.5–3.0°)
     */
    void setBacklash(int servoId, float degrees);

    /**
     * Получение величины люфта для конкретного сервопривода.
     *
     * @param servoId  индекс сервопривода (0–6)
     * @return         величина люфта в градусах
     */
    float getBacklash(int servoId) const;

    /**
     * Компенсация целевого угла с учётом люфта.
     *
     * Алгоритм:
     * 1. Вычисляется разница (delta) между целевым и текущим углом.
     * 2. Определяется направление движения:
     *    delta > 0.01° → направление +1 (по часовой стрелке)
     *    delta < -0.01° → направление -1 (против часовой стрелки)
     *    |delta| <= 0.01° → направление 0 (нет движения)
     * 3. Если направление изменилось (новое ≠ последнему) И
     *    последнее направление было ненулевым (уже двигались ранее),
     *    к целевому углу прибавляется величина люфта × направление.
     * 4. Возвращается скорректированный целевой угол.
     *
     * Порог 0.01° используется для фильтрации шума датчиков и
     * предотвращения ложных срабатываний при малых перемещениях.
     *
     * @param servoId     индекс сервопривода (0–6)
     * @param targetAngle целевой угол в градусах
     * @return            скорректированный угол с учётом люфта
     */
    float compensate(int servoId, float targetAngle);

    /**
     * Обновление направления движения после завершения перемещения.
     *
     * Вызывается после фактического перемещения сервопривода
     * для обновления внутреннего состояния компенсатора.
     *
     * Алгоритм:
     * 1. Вычисляется разница между новым и предыдущим текущим углом.
     * 2. Определяется направление движения (±1 или 0).
     * 3. Запоминается новое текущее направление и угол.
     *
     * @param servoId      индекс сервопривода (0–6)
     * @param currentAngle фактический текущий угол сервопривода
     */
    void updateDirection(int servoId, float currentAngle);

    /**
     * Массовая установка люфта для всех 7 сервоприводов.
     *
     * @param backlash  массив из 7 элементов с величинами люфта в градусах
     */
    void setAll(const float backlash[7]);

    /**
     * Массовое получение люфта для всех 7 сервоприводов.
     *
     * @param backlash  массив из 7 элементов для записи величин люфта
     */
    void getAll(float backlash[7]) const;

private:
    /**
     * Внутреннее состояние одного сервопривода для компенсации люфта.
     *
     * currentAngle — последний известный угол сервопривода (в градусах).
     *   Обновляется при вызове updateDirection() после перемещения.
     *   Используется для определения направления движения.
     *
     * lastDirection — последнее направление движения:
     *   -1  — движение против часовой стрелки (угол уменьшается)
     *    0  — нет движения (начальное состояние или остановка)
     *   +1  — движение по часовой стрелке (угол увеличивается)
     *   Используется для определения смены направления в compensate().
     *
     * backlash — величина люфта в градусах.
     *   Задаётся через setBacklash() или setAll().
     *   Значение 0 означает отсутствие компенсации для данного серво.
     */
    struct ServoState {
        float currentAngle = 0;
        int   lastDirection = 0;  // -1, 0, 1
        float backlash = 0;
    };

    /** Массив состояний для 7 сервоприводов (6 осей + захват) */
    ServoState states[7];
};
