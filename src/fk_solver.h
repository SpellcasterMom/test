/*
 * fk_solver.h — Заголовочный файл решателя прямой кинематики (FK) для 6-осевого
 *               робота-манипулятора.
 *
 * Математика расписана в KINEMATICS.md (корень репозитория) — референс,
 * менять синхронно с кодом.
 *
 * Прямая кинематика (Forward Kinematics) вычисляет положение и ориентацию
 * каждого звена (сустава) манипулятора в базовой СК по известным углам поворота
 * сочленений (углы конфигурации q[0]..q[5]).
 *
 * Методика: используется параметризация Денавита — Хартенберга (DH-параметры).
 * Каждое звено описывается четырьмя параметрами: a, alpha, d, theta_offset.
 * Матрица перехода между двумя последовательными системами координат строится
 * по формуле:
 *
 *   T = | cos(θ)  -sin(θ)·cos(α)   sin(θ)·sin(α)   a·cos(θ) |
 *       | sin(θ)   cos(θ)·cos(α)  -cos(θ)·sin(α)   a·sin(θ) |
 *       |   0         sin(α)           cos(α)            d     |
 *       |   0           0                 0               1     |
 *
 * где θ = q[i] + theta_offset — полный угол поворота i-го сочленения.
 *
 * Для получения позиции i-го сустава в базовой СК перемножаются матрицы
 * перехода от базы до этого сустава:
 *   T0i = T01 · T12 · T23 · ... · T(i-1,i)
 *
 * Конечная точка инструмента (TCP — Tool Center Point) вычисляется как позиция
 * запястья (6-й сустав) плюс длина пальца вдоль оси Z последнего звена.
 */

#pragma once

#include "types.h"
#include "config.h"

/**
 * Класс FKSolver — решатель прямой кинематики.
 *
 * Основные задачи:
 *  - Вычисление позиции любого сустава в базовой СК
 *  - Вычисление положения конца пальца (TCP) с учётом длины пальца
 *  - Получение полной матрицы перехода 4×4 или матрицы вращения 3×3
 *  - Предоставление DH-параметров для обратной кинематики
 */
class FKSolver {
public:
    FKSolver();

    /**
     * Установка DH-параметров для всех 6 звеньев.
     * @param dh — массив 6×4: [a, alpha, d, theta_offset] для каждого звена.
     *             Углы alpha и theta_offset задаются в градусах,
     *             внутри конвертируются в радианы.
     */
    void setDHParams(const float dh[6][4]);

    /**
     * Установка длин звеньев (суставов) робота.
     * @param lengths — массив из 6 целых чисел, длины в миллиметрах.
     */
    void setLinkLengths(const int lengths[6]);

    /**
     * Установка длины пальца захвата.
     * Используется при вычислении TCP: позиция запястья + длина пальца по оси Z.
     * @param len — длина пальца в миллиметрах.
     */
    void setFingerLength(float len);

    /**
     * Получение позиции конкретного сустава в базовой СК.
     * @param q     — массив углов конфигурации (6 значений в градусах).
     * @param joint — номер сустава (0 = база, 1..6 = суставы).
     * @return Вектор позиции {x, y, z} в миллиметрах.
     */
    Vec3 getJointPosition(const float q[6], int joint);

    /**
     * Получение позиций всех 7 точек (база + 6 суставов).
     * @param q     — углы конфигурации.
     * @param joints — выходной массив из 7 Vec3.
     */
    void getAllJointPositions(const float q[6], Vec3 joints[7]);

    /**
     * Получение позиции конечного эффектора (TCP — Tool Center Point).
     * TCP вычисляется как позиция запястья (сустав 6) + длина пальца
     * вдоль направления выдвижения пальца (ось Z 6-го звена).
     * @param q — углы конфигурации.
     * @return Позиция кончика пальца {x, y, z} в мм.
     */
    Vec3 getEndEffector(const float q[6]);

    /**
     * Получение направляющего вектора пальца (ось Z 6-го звена).
     * Используется для проверок безопасности и визуализации.
     * @param q — углы конфигурации.
     * @return Единичный вектор направления выдвижения пальца.
     */
    Vec3 getFingerDirection(const float q[6]);

    /**
     * Получение полной матрицы перехода 4×4 от базы до указанного сустава.
     * Матрица содержит и вращение, и перенос: T0i = T01 · T12 · ... · T(i-1,i).
     * Формула DH-матрицы (для каждого звена):
     *   | cos(θ)  -sin(θ)cos(α)   sin(θ)sin(α)   a·cos(θ) |
     *   | sin(θ)   cos(θ)cos(α)  -cos(θ)sin(α)   a·sin(θ) |
     *   |   0         sin(α)           cos(α)          d     |
     *   |   0           0                0              1     |
     * @param q          — углы конфигурации.
     * @param upToJoint  — номер последнего звена (0..5), до которого
     *                     накапливается произведение матриц.
     * @return Матрица 4×4 T0i (baseUrl → joint upToJoint).
     */
    Mat4 getTransform(const float q[6], int upToJoint);

    /**
     * Получение матрицы вращения 3×3 — верхний левый блок 3×3 матрицы T0i.
     * Ориентация сустава или конечного эффектора в базовой СК.
     * Матрица вращения представляет собой косинусы направляющих осей
     * локальной СК в базовой СК:
     *   R = | r11 r12 r13 |   — ось X локальной СК
     *       | r21 r22 r23 |   — ось Y локальной СК
     *       | r31 r32 r33 |   — ось Z локальной СК
     * @param q          — углы конфигурации.
     * @param upToJoint  — номер звена (0..5).
     * @return Матрица 4×4 с верхним левым блоком 3×3 вращения,
     *         остальные элементы — единичная матрица.
     */
    Mat4 getRotationMatrix(const float q[6], int upToJoint);

    /**
     * Получение DH-параметров (для использования в обратной кинематике).
     * @param out — выходной массив 6×4, заполняется текущими DH-параметрами.
     */
    void getDHParams(float out[6][4]) const;

private:
    float dh[6][4];    // DH-параметры: [a, alpha, d, theta_offset] для каждого звена
    int   linkLen[6];  // Длины звеньев в мм (не используются в FK напрямую)
    float fingerLength;// Длина пальца захвата в мм (добавляется к позиции запястья)

    /**
     * Построение матрицы DH-преобразования 4×4 для одного звена.
     *
     * Формула стандартной DH-матрицы:
     *   T(a, α, d, θ) =
     *     | cos(θ)  -sin(θ)·cos(α)   sin(θ)·sin(α)   a·cos(θ) |
     *     | sin(θ)   cos(θ)·cos(α)  -cos(θ)·sin(α)   a·sin(θ) |
     *     |   0         sin(α)           cos(α)            d     |
     *     |   0           0                 0               1     |
     *
     * Параметры:
     *   a     — длина звена (расстояние вдоль оси X) [мм]
     *   α     — угол закручивания (вокруг оси X) [радианы]
     *   d     — смещение вдоль оси Z [мм]
     *   θ     — угол поворота вокруг оси Z [радианы] (= q[i] + theta_offset)
     *
     * @return Матрица 4×4 перехода от (i-1)-й СК к i-й СК.
     */
    Mat4 dhTransform(float a, float alpha, float d, float theta);

    /**
     * Вычисление прямой кинематики — произведение DH-матриц от базы
     * до указанного сустава.
     *
     * Алгоритм:
     *   T = E (единичная матрица 4×4)
     *   для i = 0 .. upToJoint:
     *     θ = q[i] (градусы) + theta_offset (градусы) → радианы
     *     Ti = dhTransform(a_i, α_i, d_i, θ_i)
     *     T = T × Ti   (накопление преобразований)
     *
     * Результат T = T0,upToJoint — матрица перехода от базы до сустава upToJoint.
     *
     * @param q          — углы конфигурации (градусы).
     * @param upToJoint  — индекс последнего звена (0..5).
     * @return Матрица 4×4 T0i.
     */
    Mat4 computeFK(const float q[6], int upToJoint);
};
