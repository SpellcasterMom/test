#pragma once

#include "types.h"
#include "config.h"
#include "fk_solver.h"

/**
 * Класс IKSolver — решатель обратной кинематики.
 *
 * Алгоритм работы:
 *   1. По заданной целевой позе (x, y, z, roll, pitch, yaw) вычисляются
 *      углы поворота шести суставов манипулятора.
 *   2. Сначала методом solvePosition() определяются углы первых трёх
 *      суставов (q1, q2, q3) для достижения целевой позиции конца звена.
 *      Это делается геометрически — через проекцию задачи на плоскость
 *      и применение теоремы косинусов для двухзвенного манипулятора.
 *   3. Затем методом solveOrientation() вычисляются углы последних трёх
 *      суставов (q4, q5, q6), образующих сферическое запястье (spherical wrist).
 *      Используется матричный подход: из желаемой ориентации (R06) вычитается
 *      вклад первых трёх суставов (R03), полученная матрица R36 декомпозируется
 *      на углы Эйлера ZYX.
 *
 * ВАЖНО (Last modify: 2026-09-25):
 *   IK решает позицию ЗАПЯСТЬЯ, а не TCP. Длина пальца (fingerLength)
 *   вычитается из целевой позиции TCP перед вызовом solvePosition().
 *   Это устраняет ошибку ~20 мм, когда G0 X100 Y100 Z100 давало
 *   Position X=83 Y=127 Z=116.
 */
class IKSolver {
public:
    IKSolver();

    /** Установка DH-параметров (a, alpha, d) для шести звеньев */
    void setDHParams(const float dh[6][4]);

    /** Установка длин звеньев (используются для геометрического решения) */
    void setLinkLengths(const int lengths[6]);

    /** Установка механических ограничений сервоприводов */
    void setServoLimits(const ServoConfig servos[7]);

    /**
     * Установка длины пальца захвата.
     *
     * Длина пальца вычитается из целевой позиции TCP перед решением
     * задачи позиции (solvePosition). Так IK решает для ЗАПЯСТЬЯ,
     * а не для TCP. Без этой коррекции G0 X100 Y100 Z100 даёт ошибку
     * ~20 мм из-за смещения TCP относительно запястья.
     *
     * @param len — длина пальца в мм
     */
    void setFingerLength(float len) { fingerLength = len; }

    /**
     * Основной метод решения обратной кинематики.
     *
     * @param target  — целевая поза (позиция + ориентация в Эйлерах ZYX)
     * @param result  — выходные углы суставов q1–q6
     * @return true, если решение найдено и находится в допустимых пределах
     */
    bool solve(const Pose &target, JointAngles &result);

    /**
     * Проверка достижимости целевой позиции.
     * Решает только задачу позиции (q1–q3) и проверяет, попадает ли
     * целевая точка в рабочее пространство манипулятора.
     */
    bool isReachable(const Pose &target);

    /**
     * Поиск всех возможных решений (elbow up / elbow down).
     *
     * Для задачи позиции существуют два решения (прямая и обратная конфигурация
     * двухзвенного манипулятора). Каждое решение дополняется решением задачи
     * ориентации.
     *
     * @param target     — целевая поза
     * @param solutions  — массив найденных решений (максимум 4)
     * @return количество найденных решений
     */
    int solveAll(const Pose &target, JointAngles solutions[4]);

private:
    /* DH-параметры: a — длина звена, alpha — угол поворота, d — смещение */
    float a[6];
    float alpha[6];
    float d[6];

    /* Длины звеньев (для геометрического IK) */
    int   linkLen[6];

    /* Ограничения углов сервоприводов (мин/макс для каждого из 7 каналов) */
    ServoConfig servoLimits[7];

    /* Длина пальца захвата (мм). Вычитается из TCP → запястье в solve(). */
    float fingerLength;

    /* Решатель прямой кинематики (используется для проверки решений) */
    FKSolver fkSolver;

    /**
     * Геометрическое решение задачи позиции (суставы q1, q2, q3).
     *
     * Алгоритм:
     *   1) Вычисляется угол поворота основания q1 = atan2(y, x)
     *   2) Задача проецируется на 2D-плоскость (r, s), где:
     *      r = sqrt(x² + y²) - a0  (горизонтальное расстояние минус смещение основания)
     *      s = z - d0               (вертикальное расстояние минус высота основания)
     *   3) Для двухзвенного манипулятора (L1 = плечо, L2 = локоть) применяется
     *      теорема косинусов для нахождения угла q3:
     *        cos(q3) = (r² + s² - L1² - L2²) / (2·L1·L2)
     *   4) Угол плеча q2 вычисляется через разность углов:
     *        q2 = atan2(s, r) - atan2(L2·sin(q3), L1 + L2·cos(q3))
     *
     * ВНИМАНИЕ: (x, y, z) — это позиция ЗАПЯСТЬЯ, а не TCP.
     *
     * @param x, y, z — целевая позиция запястья
     * @param q1, q2, q3 — выходные углы суставов (в градусах)
     * @return true если точка достижима
     */
    bool solvePosition(float x, float y, float z, float &q1, float &q2, float &q3);

    /**
     * Решение задачи ориентации (суставы q4, q5, q6) методом DH-декомпозиции.
     *
     * Алгоритм:
     *   1) Вычисляется матрица поворота R03 (от основания до 3-го сустава)
     *      как произведение DH-матриц трансформаций: R03 = T01 · T12 · T23
     *   2) Желаемая ориентация конца инструмента (ROLL, PITCH, YAW) преобразуется
     *      в матрицу поворота R06 с помощью функции eulerToMatrix()
     *   3) Вычисляется матрица ориентации запястья: R36 = R03⁻¹ · R06
     *   4) Матрица R36 декомпозируется на углы Эйлера ZYX методом decomposeRotation()
     *
     * @param A, B, C — целевые углы Эйлера (roll, pitch, yaw) в градусах
     * @param q1, q2, q3 — уже вычисленные углы первых трёх суставов
     * @param q4, q5, q6 — выходные углы запястья (в градусах)
     * @return true если декомпозиция выполнена
     */
    bool solveOrientation(float A, float B, float C, float q1, float q2, float q3,
                          float &q4, float &q5, float &q6);

    /**
     * Ограничение угла углами механических ограничений сервопривода.
     * Если угол выходит за пределы [minAngle, maxAngle], он обрезается
     * до ближайшей допустимой границы.
     */
    float clampAngle(int servoId, float angle);

    /**
     * Преобразование углов Эйлера ZYX в матрицу поворота 4×4.
     *
     * R = Rz(yaw) · Ry(pitch) · Rx(roll)
     */
    Mat4 eulerToMatrix(float roll, float pitch, float yaw);

    /**
     * Декомпозиция матрицы поворота R36 на углы Эйлера ZYX.
     *
     * R36 = Rz(q5) · Ry(q4) · Rx(q6)
     *
     * Особый случай: замок кардана (gimbal lock), когда pitch = ±90°.
     */
    void decomposeRotation(const Mat4 &R, float &q4, float &q5, float &q6);

    /** Транспонирование матрицы 4×4: r[i][j] = m[j][i] */
    Mat4 matTranspose(const Mat4 &m);

    /** Умножение матриц 4×4: r = a · b (классический алгоритм тройного цикла) */
    Mat4 matMultiply(const Mat4 &a, const Mat4 &b);
};