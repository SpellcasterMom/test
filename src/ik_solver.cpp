/**
 * Транспонирование матрицы 4×4.
 *
 * Операция замены строк и столбцов матрицы: r[i][j] = m[j][i].
 * Для ортогональных матриц поворота транспонирование эквивалентно
 * обратной матрице: R⁻¹ = Rᵀ. Это свойство используется в solveOrientation()
 * для вычисления R03⁻¹ = R03ᵀ при расчёте R36 = R03ᵀ · R06.
 *
 * @param m — исходная матрица 4×4
 * @return транспонированная матрица 4×4
 */
Mat4 IKSolver::matTranspose(const Mat4 &m) {
    Mat4 r;
    for (int i = 0; i < 4; i++)
        for (int j = 0; j < 4; j++)
            r.m[i][j] = m.m[j][i];  // обмен строк и столбцов
    return r;
}

/**
 * Умножение двух матриц 4×4: r = a · b.
 *
 * Классический алгоритм умножения матриц с тройным циклом:
 *   r[i][j] = Σ(k=0..3) a[i][k] · b[k][j]
 *
 * Используется для:
 *   - Вычисления произведения DH-матриц: T03 = T01 · T12 · T23
 *   - Вычисления R36 = R03ᵀ · R06
 *   - Построения матриц поворота из Эйлеровых углов
 */
Mat4 IKSolver::matMultiply(const Mat4 &a, const Mat4 &b) {
    Mat4 r;
    for (int i = 0; i < 4; i++)
        for (int j = 0; j < 4; j++)
            for (int k = 0; k < 4; k++)
                r.m[i][j] += a.m[i][k] * b.m[k][j];
    return r;
}

