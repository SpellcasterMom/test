/**
 * Основной метод solve() — двухэтапное решение обратной кинематики.
 *
 * ВХОД: целевая поза target = (x, y, z, roll, pitch, yaw)
 * ВЫХОД: углы суставов result = (q1, q2, q3, q4, q5, q6, gripper)
 *
 * ЭТАП 1 — ПОЗИЦИЯ (метод solvePosition):
 *   Решает задачу определения углов q1, q2, q3 для достижения
 *   целевой позиции (x, y, z) конца звена (wrist center).
 *   Использует геометрический подход с проекцией на 2D-плоскость.
 *
 * ЭТАП 2 — ОРИЕНТАЦИЯ (метод solveOrientation):
 *   Решает задачу определения углов q4, q5, q6 для достижения
 *   целевой ориентации (roll, pitch, yaw) при уже известных q1–q3.
 *   Использует DH-декомпозицию: R36 = R03⁻¹ · R06, затем
 *   декомпозицию R36 на углы Эйлера ZYX.
 *
 * ПОСТ-ОБРАБОТКА:
 *   Каждый угол обрезается (clamp) по механическим ограничениям
 *   соответствующего сервопривода для предотвращения повреждения.
 *
 * @param target — целевая поза (позиция + ориентация)
 * @param result — массив углов суставов (6 суставов + захват)
 * @return true если решение найдено, false если позиция недостижима
 */
bool IKSolver::solve(const Pose &target, JointAngles &result) {
    float q1, q2, q3, q4, q5, q6;

    // ================================================================
    // ЭТАП 1: Решение задачи позиции (суставы 1–3)
    // ================================================================
    // Определяем углы поворота основания (q1), плеча (q2) и локтя (q3)
    // для достижения целевой позиции (x, y, z).
    // Если точка находится вне рабочего пространства — возвращаем false.
    if (!solvePosition(target.position.x, target.position.y, target.position.z,
                       q1, q2, q3)) {
        return false;
    }

    // ================================================================
    // ЭТАП 2: Решение задачи ориентации (суставы 4–6)
    // ================================================================
    // Вычисляем углы запястья (q4, q5, q6) для достижения
    // целевой ориентации (roll, pitch, yaw) при известных q1–q3.
    // Используем DH-декомпозицию: R36 = R03⁻¹ · R06
    solveOrientation(target.orientation.x, target.orientation.y, target.orientation.z,
                     q1, q2, q3, q4, q5, q6);

    // ================================================================
    // ПОСТ-ОБРАБОТКА: Ограничение углов механическими пределами
    // ================================================================
    // Каждый угол обрезается до допустимого диапазона [minAngle, maxAngle]
    // для соответствующего сервопривода. Это предотвращает повреждение
    // манипулятора при выходе за пределы хода.
    result.angles[0] = clampAngle(0, q1);  // основание
    result.angles[1] = clampAngle(1, q2);  // плечо
    result.angles[2] = clampAngle(2, q3);  // локоть
    result.angles[3] = clampAngle(3, q4);  // запястье (pitch)
    result.angles[4] = clampAngle(4, q5);  // запястье (yaw)
    result.angles[5] = clampAngle(5, q6);  // запястье (roll)
    result.angles[6] = 0;  // захват управляется отдельно

    return true;
}

