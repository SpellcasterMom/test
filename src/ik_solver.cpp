// ГЕОМЕТРИЧЕСКОЕ РЕШЕНИЕ ЗАДАЧИ ПОЗИЦИИ (СУСТАВЫ 1–3)
// ============================================================================

/**
 * Геометрическое решение задачи позиции (суставы q1, q2, q3).
 *
 * ЗАДАЧА: Найти углы q1, q2, q3, чтобы конец 3-го звена (запястье)
 *         оказался в точке (x, y, z).
 *
 * АЛГОРИТМ:
 *
 * ШАГ 1: УГОЛ ОСНОВАНИЯ (q1)
 *   Поворот основания вокруг оси Z определяется целевыми координатами x, y:
 *     q1 = atan2(y, x)
 *   Это угол в горизонтальной плоскости от оси X до проекции целевой точки.
 *
 * ШАГ 2: ПРОЕКЦИЯ НА 2D-ПЛОСКОСТЬ
 *   Задача сводится к двухзвенному манипулятору в вертикальной плоскости:
 *     r = sqrt(x² + y²) − a0   (горизонтальное расстояние от оси вращения
 *                                 плеча до целевой точки, минус смещение основания)
 *     s = z − d0                (вертикальное расстояние от плеча до целевой точки,
 *                                 минус высота основания)
 *
 * ШАГ 3: ПРОВЕРКА ДОСТИЖИМОСТИ
 *   Точка достижима, если расстояние до неё от плеча находится в пределах:
 *     |L1 − L2| ≤ dist ≤ L1 + L2
 *   где dist = sqrt(r² + s²), L1 — длина плеча, L2 — длина локтя.
 *   Если dist > L1 + L2 — точка слишком далеко.
 *   Если dist < |L1 − L2| — точка слишком близко.
 *
 * ШАГ 4: УГОЛ ЛОКТЯ (q3) ПО ТЕОРЕМЕ КОСИНУСОВ
 *   Рассматривая треугольник из трёх сторон (L1, L2, dist), находим:
 *     cos(q3) = (r² + s² − L1² − L2²) / (2 · L1 · L2)
 *   Знак q3 определяет конфигурацию:
 *     q3 < 0 — «肘 вниз» (elbow down, стандартная конфигурация)
 *     q3 > 0 — «肘 вверх» (elbow up, альтернативная конфигурация)
 *
 * ШАГ 5: УГОЛ ПЛЕЧА (q2)
 *   Вычисляется как разность двух углов:
 *     q2 = atan2(s, r) − atan2(L2 · sin(q3), L1 + L2 · cos(q3))
 *   Первый угол — направление на цель из плеча.
 *   Второй угол — коррекция из-за угла локтя.
 *
 * @param x, y, z — целевая позиция (мм)
 * @param q1, q2, q3 — выходные углы суставов (градусы)
 * @return true если точка достижима, false если нет
 */
bool IKSolver::solvePosition(float x, float y, float z, float &q1, float &q2, float &q3) {
    // DH-параметры основания
    float d0 = d[0];  // высота основания (110 мм) — смещение вдоль оси Z
    float a0 = a[0];  // смещение основания (25 мм) — длина звена основания

    // ==================================================================
    // ШАГ 1: Угол поворота основания (q1)
    // ==================================================================
    // atan2(y, x) даёт угол от оси X до проекции целевой точки
    // на горизонтальную плоскость. Этот угол определяет, куда
    // «смотрит» плечо манипулятора.
    q1 = atan2(y, x);

    // ==================================================================
    // ШАГ 2: Проекция на 2D-плоскость (r, s)
    // ==================================================================
    // r — горизонтальное расстояние от вертикальной оси вращения
    //     основания до целевой точки (за вычетом смещения a0)
    // s — вертикальное расстояние от оси вращения плеча до целевой точки
    //     (за вычетом высоты основания d0)
    float r = sqrt(x * x + y * y) - a0;
    float s = z - d0;

    // ==================================================================
    // ШАГ 3: Длины звеньев двухзвенного манипулятора
    // ==================================================================
    // L1 — длина плеча (от плеча до локтя) = DH параметр a[1]
    // L2 — длина локтя (от локтя до запястья) = DH параметр a[2]
    float L1 = a[1];  // 160 мм (плечо — локоть)
    float L2 = a[2];  // 155 мм (локоть — запястье)

    // Расстояние от плеча до целевой точки в 2D-проекции
    float dist = sqrt(r * r + s * s);

    // ==================================================================
    // ШАГ 4: Проверка достижимости
    // ==================================================================
    // Условие достижимости для двухзвенного манипулятора:
    //   |L1 − L2| ≤ dist ≤ L1 + L2
    // Если расстояние выходит за эти пределы, точка недостижима.
    if (dist > (L1 + L2)) return false;  // слишком далеко
    if (dist < fabs(L1 - L2)) return false;  // слишком близко

    // ==================================================================
    // ШАГ 5: Угол локтя (q3) по теореме косинусов
    // ==================================================================
    // Рассматривая треугольник со сторонами L1, L2 и dist:
    //   cos(q3) = (r² + s² − L1² − L2²) / (2 · L1 · L2)
    //
    // Это прямое применение теоремы косинусов:
    //   dist² = L1² + L2² − 2·L1·L2·cos(π − q3)
    //   dist² = L1² + L2² + 2·L1·L2·cos(q3)  (т.к. cos(π−α) = −cos(α))
    float cosQ3 = (r * r + s * s - L1 * L1 - L2 * L2) / (2.0f * L1 * L2);

    // Ограничение значений cosQ3 в пределах [-1, 1] для численной устойчивости
    // (из-за округлений cosQ3 может略微 выйти за пределы)
    cosQ3 = constrain(cosQ3, -1.0f, 1.0f);

    // Выбираем решение «肘 вниз» (q3 отрицательный).
    // Для решения «肘 вверх» нужно изменить знак: q3 = +acos(cosQ3)
    q3 = -acos(cosQ3);

    // ==================================================================
    // ШАГ 6: Угол плеча (q2)
    // ==================================================================
    // Угол плеча вычисляется как разность двух углов:
    //   q2 = atan2(s, r) − atan2(S, C)
    //
    // Где:
    //   atan2(s, r) — угол от горизонтали до прямой «плечо → цель»
    //   atan2(S, C) — угол, на который нужно «подтянуть» плечо из-за
    //                  угла локтя q3
    //
    // S = L2 · sin(q3) — проекция локтя на вертикаль
    // C = L1 + L2 · cos(q3) — проекция локтя на горизонталь
    float sinQ3 = sin(q3);
    float C = L1 + L2 * cosQ3;  // горизонтальная проекция
    float S = L2 * sinQ3;       // вертикальная проекция

    q2 = atan2(s, r) - atan2(S, C);

    // ==================================================================
    // ШАГ 7: Перевод из радиан в градусы
    // ==================================================================
    // Все вычисления выше выполнялись в радианах (стандарт для math.h),
    // но выходные углы должны быть в градусах для управления сервоприводами.
    q1 = q1 * RAD_TO_DEG;
    q2 = q2 * RAD_TO_DEG;
    q3 = q3 * RAD_TO_DEG;

    return true;
}

