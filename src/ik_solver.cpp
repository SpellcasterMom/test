/**
 * Ограничение угла механическими пределами сервопривода.
 *
 * Каждый сервопривод имеет физические ограничения по углу поворота
 * (minAngle, maxAngle). Если вычисленный угол выходит за эти пределы,
 * он обрезается (clamp) до ближайшей допустимой границы.
 *
 * Это предотвращает:
 *   - Повреждение сервопривода (выход за механический упор)
 *   - Повреждение манипулятора (столкновение звеньев)
 *   - Некорректную работу (сервопривод не может достичь заданного угла)
 *
 * Функция constrain() определена в types.h и реализует:
 *   if (angle < min) return min;
 *   if (angle > max) return max;
 *   return angle;
 *
 * @param servoId — номер сервопривода (0–6)
 * @param angle   — вычисленный угол (градусы)
 * @return угол, обрезанный до [minAngle, maxAngle]
 */
float IKSolver::clampAngle(int servoId, float angle) {
    float minA = servoLimits[servoId].minAngle;  // минимальный угол (градусы)
    float maxA = servoLimits[servoId].maxAngle;  // максимальный угол (градусы)
    return constrain(angle, minA, maxA);  // обрезка до допустимого диапазона
}
