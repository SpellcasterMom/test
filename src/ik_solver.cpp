// ПОИСК ВСЕХ ВОЗМОЖНЫХ РЕШЕНИЙ (肘 ВВЕРХ / 肘 ВНИЗ)
// ============================================================================

/**
 * Поиск всех возможных решений обратной кинематики.
 *
 * Для задачи позиции (суставы 1–3) существует два решения:
 *   1) «肘 вниз» (elbow down) — q3 < 0, стандартная конфигурация
 *   2) «肘 вверх» (elbow up)  — q3 > 0, альтернативная конфигурация
 *
 * Для каждого решения задачи позиции вычисляется соответствующее
 * решение задачи ориентации (суставы 4–6).
 *
 * В результате может быть получено до 2 решений (elbow up/down).
 *
 * Примечание: в текущей реализации решение «肘 вверх» получается
 * инверсией угла q3 (q3 = -q3). Это корректно для случая, когда
 * L1 ≠ L2 (что выполняется для данного манипулятора: L1=160, L2=155).
 *
 * @param target     — целевая поза
 * @param solutions  — массив найденных решений (максимум 4, но обычно 1–2)
 * @return количество найденных решений (0, 1 или 2)
 */
int IKSolver::solveAll(const Pose &target, JointAngles solutions[4]) {
    int count = 0;
    float q1, q2, q3, q4, q5, q6;

    // ================================================================
    // РЕШЕНИЕ 1: 肘 вниз (elbow down, q3 < 0)
    // ================================================================
    // Стандартная конфигурация: локоть «смотрит вниз».
    // solvePosition() по умолчанию возвращает решение с q3 < 0.
    if (solvePosition(target.position.x, target.position.y, target.position.z,
                      q1, q2, q3)) {
        // Решаем задачу ориентации для найденных q1–q3
        solveOrientation(target.orientation.x, target.orientation.y, target.orientation.z,
                         q1, q2, q3, q4, q5, q6);
        // Сохраняем полное решение (6 углов + захват)
        solutions[count].setAll(q1, q2, q3, q4, q5, q6, 0);
        count++;
    }

    // ================================================================
    // РЕШЕНИЕ 2: 肘 вверх (elbow up, q3 > 0)
    // ================================================================
    // Альтернативная конфигурация: локоть «смотрит вверх».
    // Получается инверсией угла q3 (из отрицательного в положительный).
    // При инверсии q3 меняется и конфигурация плеча (q2),
    // но поскольку solveOrientation() пересчитывает q4–q6 для
    // новых q1–q3, решение корректно.
    if (solvePosition(target.position.x, target.position.y, target.position.z,
                      q1, q2, q3)) {
        q3 = -q3;  // инвертируем угол локтя:肘 вниз →肘 вверх
        // Пересчитываем ориентацию для новой конфигурации
        solveOrientation(target.orientation.x, target.orientation.y, target.orientation.z,
                         q1, q2, q3, q4, q5, q6);
        solutions[count].setAll(q1, q2, q3, q4, q5, q6, 0);
        count++;
    }

    return count;
}

