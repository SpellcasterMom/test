/**
 * Декомпозиция матрицы поворота R36 на углы Эйлера ZYX (q4, q5, q6).
 *
 * Матрица R36 описывает ориентацию запястья (суставов 4–6) относительно
 * системы координат 3-го сустава. Декомпозиция выполняется по формулам
 * для последовательности ZYX:
 *
 *   R36 = Rz(q5) · Ry(q4) · Rx(q6)
 *
 * Где:
 *   q4 (pitch / тангаж) — поворот вокруг оси Y
 *   q5 (yaw / рыскание) — поворот вокруг оси Z
 *   q6 (roll / крен)    — поворот вокруг оси X
 *
 * Извлечение углов:
 *   sin(q4) = -R[2][0]  →  q4 = asin(-R[2][0])
 *   q5 = atan2(R[2][1], R[2][2])  (cos(q4) ≠ 0)
 *   q6 = atan2(R[1][0], R[0][0])  (cos(q4) ≠ 0)
 *
 * ОСОБЫЙ СЛУЧАЙ: ЗАМОК КАРДАНА (GIMBAL LOCK)
 * Когда q4 = ±90°, cos(q4) = 0 и оси вращения вокруг X и Z совпадают.
 * В этом случае:
 *   - Теряется одна степень свободы
 *   - Углы q5 и q6 становятся зависимыми (могут сложиться в один поворот)
 *   - Для корректного решения фиксируем один из углов (q6 = 0)
 *     и вычисляем второй через atan2 из соответствующих элементов матрицы
 *
 * @param R   — матрица поворота запястья R36 (4×4)
 * @param q4  — выходной угол: pitch / тангаж (в градусах)
 * @param q5  — выходной угол: yaw / рыскание (в градусах)
 * @param q6  — выходной угол: roll / крен (в градусах)
 */
void IKSolver::decomposeRotation(const Mat4 &R, float &q4, float &q5, float &q6) {
    // Извлечение sin(pitch) из элемента R[2][0] матрицы ZYX
    // По формуле: R[2][0] = -sin(θ), следовательно sin(θ) = -R[2][0]
    float sp = -R.m[2][0];  // sin(pitch) = sin(q4)

    // Проверка на замок кардана: pitch ≈ ±90°
    // При pitch = +90°: sin(pitch) ≈ 1, cos(pitch) ≈ 0
    // При pitch = -90°: sin(pitch) ≈ -1, cos(pitch) ≈ 0
    // Порог 0.9999 chosen для числовой устойчивости
    if (sp > 0.9999f) {
        // ============================================
        // ЗАМОК КАРДАНА: pitch = +90°
        // ============================================
        // Когда pitch = +90°, оси X и Z поворотов совпадают,
        // и мы не можем разделить roll и yaw.
        // Решение: фиксируем roll (q6) = 0 и вычисляем yaw (q5)
        // из оставшихся элементов матрицы.
        //
        // При pitch = +90° матрица упрощается:
        //   R[0][1] = -sin(yaw - roll)
        //   R[1][1] =  cos(yaw - roll)
        // Вычисляем yaw - roll = atan2(R[0][1], R[1][1]),
        // затем roll = 0, yaw = atan2(R[0][1], R[1][1])
        q4 = 90.0f;  // pitch = +90°
        q5 = atan2(R.m[0][1], R.m[1][1]) * RAD_TO_DEG;  // yaw
        q6 = 0.0f;   // roll фиксируется (произвольный выбор)
    } else if (sp < -0.9999f) {
        // ============================================
        // ЗАМОК КАРДАНА: pitch = -90°
        // ============================================
        // Аналогичный случай, но с знаком:
        //   R[0][1] = sin(yaw + roll)
        //   R[1][1] = cos(yaw + roll)
        // Вычисляем yaw + roll, затем roll = 0
        q4 = -90.0f;  // pitch = -90°
        q5 = atan2(-R.m[0][1], R.m[1][1]) * RAD_TO_DEG;  // yaw
        q6 = 0.0f;   // roll фиксируется
    } else {
        // ============================================
        // ОБЫЧНЫЙ СЛУЧАЙ: |sin(pitch)| < 1
        // ============================================
        // cos(q4) ≠ 0, поэтому все три угла определяются однозначно
        //
        // q4 (pitch): из sin(pitch) = -R[2][0]
        q4 = asin(sp) * RAD_TO_DEG;

        // q5 (yaw): из элементов R[2][1] и R[2][2]
        // R[2][1] = cos(pitch)·sin(yaw), R[2][2] = cos(pitch)·cos(yaw)
        // yaw = atan2(sin(yaw)·cos(pitch), cos(yaw)·cos(pitch))
        q5 = atan2(R.m[2][1], R.m[2][2]) * RAD_TO_DEG;

        // q6 (roll): из элементов R[1][0] и R[0][0]
        // R[1][0] = sin(yaw)·cos(pitch), R[0][0] = cos(yaw)·cos(pitch)
        // roll = atan2(R[1][0], R[0][0]) — это работает благодаря
        // свойствам матрицы ZYX при cos(pitch) ≠ 0
        q6 = atan2(R.m[1][0], R.m[0][0]) * RAD_TO_DEG;
    }
}

