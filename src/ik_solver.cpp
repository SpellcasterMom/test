// ПРЕОБРАЗОВАНИЕ ЭЙЛЕРОВЫХ УГЛОВ (ZYX) В МАТРИЦУ ПОВОРОТА
// ============================================================================

/**
 * Преобразование углов Эйлера ZYX в матрицу поворота 4×4.
 *
 * Порядок обхода осей (внутри-наружу): X → Y → Z
 *   1) Rx(roll)  — поворот вокруг оси X (крен, φ)
 *   2) Ry(pitch) — поворот вокруг оси Y (тангаж, θ)
 *   3) Rz(yaw)   — поворот вокруг оси Z (рыскание, ψ)
 *
 * Итоговая матрица: R = Rz(ψ) · Ry(θ) · Rx(φ)
 *
 * Явные формулы элементов матрицы:
 *   R[0][0] = cos(ψ)·cos(θ)
 *   R[0][1] = cos(ψ)·sin(θ)·sin(φ) − sin(ψ)·cos(φ)
 *   R[0][2] = cos(ψ)·sin(θ)·cos(φ) + sin(ψ)·sin(φ)
 *   R[1][0] = sin(ψ)·cos(θ)
 *   R[1][1] = sin(ψ)·sin(θ)·sin(φ) + cos(ψ)·cos(φ)
 *   R[1][2] = sin(ψ)·sin(θ)·cos(φ) − cos(ψ)·sin(φ)
 *   R[2][0] = −sin(θ)
 *   R[2][1] = cos(θ)·sin(φ)
 *   R[2][2] = cos(θ)·cos(φ)
 *
 * @param roll  — крен (φ) в радианах
 * @param pitch — тангаж (θ) в радианах
 * @param yaw   — рыскание (ψ) в радианах
 * @return матрица поворота 4×4 (нижняя строка = [0, 0, 0, 1])
 */
Mat4 IKSolver::eulerToMatrix(float roll, float pitch, float yaw) {
    // Предвычисление синусов и косинусов для оптимизации
    float cr = cos(roll),  sr = sin(roll);    // крен: cos(φ), sin(φ)
    float cp = cos(pitch), sp = sin(pitch);   // тангаж: cos(θ), sin(θ)
    float cy = cos(yaw),   sy = sin(yaw);     // рыскание: cos(ψ), sin(ψ)

    Mat4 R;

    // Формула произведения Rz · Ry · Rx (ZYX Euler angles)
    //
    // Первый столбец (влияние yaw и pitch):
    R.m[0][0] = cy*cp;                         // cos(ψ)·cos(θ)
    R.m[1][0] = sy*cp;                         // sin(ψ)·cos(θ)
    R.m[2][0] = -sp;                           // −sin(θ)

    // Второй столбец (влияние yaw, pitch и roll):
    R.m[0][1] = cy*sp*sr - sy*cr;              // cos(ψ)·sin(θ)·sin(φ) − sin(ψ)·cos(φ)
    R.m[1][1] = sy*sp*sr + cy*cr;              // sin(ψ)·sin(θ)·sin(φ) + cos(ψ)·cos(φ)
    R.m[2][1] = cp*sr;                         // cos(θ)·sin(φ)

    // Третий столбец (влияние yaw, pitch и roll):
    R.m[0][2] = cy*sp*cr + sy*sr;              // cos(ψ)·sin(θ)·cos(φ) + sin(ψ)·sin(φ)
    R.m[1][2] = sy*sp*cr - cy*sr;              // sin(ψ)·sin(θ)·cos(φ) − cos(ψ)·sin(φ)
    R.m[2][2] = cp*cr;                         // cos(θ)·cos(φ)

    // Четвёртый столбец и четвёртая строка — однородные координаты
    R.m[3][3] = 1.0f;

    return R;
}

