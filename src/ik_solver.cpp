// РЕШЕНИЕ ЗАДАЧИ ОРИЕНТАЦИИ (СУСТАВЫ 4–6): DH-ДЕКОМПОЗИЦИЯ
// ============================================================================

/**
 * Решение задачи ориентации (суставы q4, q5, q6) методом DH-декомпозиции.
 *
 * ЗАДАЧА: Найти углы q4, q5, q6, чтобы запястье манипулятора имело
 *         целевую ориентацию (roll, pitch, yaw) при уже известных q1–q3.
 *
 * МАТЕМАТИЧЕСКАЯ ОСНОВА:
 *   Кинематическая цепь манипулятора описывается матрицами DH-трансформаций.
 *   Общая матрица трансформации от основания до конца инструмента:
 *     T06 = T01 · T12 · T23 · T34 · T45 · T56
 *
 *   Для сферического запястья (суставы 4–6) матрица R06分解на:
 *     R06 = R03 · R36
 *   Где R36 — матрица ориентации запястья, определяемая суставами 4–6.
 *
 * АЛГОРИТМ:
 *
 * ШАГ 1: Вычисление R03 (поворот от основания до 3-го сустава)
 *   Строим матрицы DH-трансформаций T01, T12, T23 и перемножаем:
 *     T03 = T01 · T12 · T23
 *   R03 — верхняя левая 3×3 подматрица T03.
 *
 * ШАГ 2: Вычисление R06 из целевой ориентации
 *   Желаемые углы Эйлера (roll, pitch, yaw) преобразуются
 *   в матрицу поворота R06 с помощью eulerToMatrix().
 *
 * ШАГ 3: Вычисление матрицы запястья R36
 *   Из R06 = R03 · R36 следует R36 = R03⁻¹ · R06.
 *   Поскольку R03 — ортогональная матрица, R03⁻¹ = R03ᵀ (транспонирование).
 *     R36 = R03ᵀ · R06
 *
 * ШАГ 4: Декомпозиция R36 на углы Эйлера ZYX
 *   Матрица R36 = Rz(q5) · Ry(q4) · Rx(q6) декомпозируется
 *   методом decomposeRotation() с обработкой замка кардана.
 *
 * DH-МАТРИЦЫ ТРАНСФОРМАЦИЙ:
 *   Общая DH-матрица трансформации для сустава i:
 *     Ti(i-1)i = [cos(θ)  -sin(θ)·cos(α)   sin(θ)·sin(α)  a·cos(θ)]
 *                 [sin(θ)   cos(θ)·cos(α)  -cos(θ)·sin(α)  a·sin(θ)]
 *                 [  0        sin(α)           cos(α)          d     ]
 *                 [  0          0                 0             1     ]
 *
 * @param A, B, C — целевые углы Эйлера (roll, pitch, yaw) в градусах
 * @param q1, q2, q3 — уже вычисленные углы первых трёх суставов (градусы)
 * @param q4, q5, q6 — выходные углы запястья (градусы)
 * @return true (декомпозиция всегда выполняется, замок кардана обрабатывается)
 */
bool IKSolver::solveOrientation(float A, float B, float C,
                                 float q1, float q2, float q3,
                                 float &q4, float &q5, float &q6) {
    // A = roll (крен), B = pitch (тангаж), C = yaw (рыскание)
    // Целевая ориентация конца инструмента в градусах

    // ================================================================
    // ШАГ 1: Вычисление матрицы R03 (поворот от основания до 3-го сустава)
    // ================================================================
    // Перевод углов q1–q3 из градусов в радианы для вычисления
    //三角函数 (sin, cos)
    float q1r = q1 * DEG_TO_RAD;
    float q2r = q2 * DEG_TO_RAD;
    float q3r = q3 * DEG_TO_RAD;

    // --------------------------------------------------
    // DH-матрица трансформации T01 (основание → сустав 1)
    // --------------------------------------------------
    // Сустав 1: вращение вокруг оси Z (угол q1)
    // DH-параметры: a[0]=25мм, alpha[0]=90°, d[0]=110мм
    //
    // alpha[0]=90° означает, что ось Z1 (вращения сустава 2)
    // перпендикулярна оси Z0 (вращения сустава 1)
    float c1 = cos(q1r), s1 = sin(q1r);
    float ca1 = cos(alpha[0] * DEG_TO_RAD), sa1 = sin(alpha[0] * DEG_TO_RAD);
    Mat4 T01;
    // Столбец 1: проекция осей X1, Y1, Z1 на систему координат 0
    T01.m[0][0] = c1;    T01.m[0][1] = -s1*ca1;  T01.m[0][2] = s1*sa1;  T01.m[0][3] = a[0]*c1;
    T01.m[1][0] = s1;    T01.m[1][1] = c1*ca1;   T01.m[1][2] = -c1*sa1; T01.m[1][3] = a[0]*s1;
    T01.m[2][0] = 0;     T01.m[2][1] = sa1;       T01.m[2][2] = ca1;     T01.m[2][3] = d[0];
    T01.m[3][3] = 1;

    // --------------------------------------------------
    // DH-матрица трансформации T12 (сустав 1 → сустав 2)
    // --------------------------------------------------
    // Сустав 2: вращение вокруг оси Z (угол q2)
    // DH-параметры: a[1]=160мм, alpha[1]=0°, d[2]=0мм
    //
    // alpha[1]=0° означает, что оси Z1 и Z2 параллельны
    // (оба сустава вращаются в параллельных плоскостях)
    float c2 = cos(q2r), s2 = sin(q2r);
    float ca2 = cos(alpha[1] * DEG_TO_RAD);
    Mat4 T12;
    T12.m[0][0] = c2;    T12.m[0][1] = -s2*ca2;  T12.m[0][2] = 0;  T12.m[0][3] = a[1]*c2;
    T12.m[1][0] = s2;    T12.m[1][1] = c2*ca2;   T12.m[1][2] = 0;  T12.m[1][3] = a[1]*s2;
    T12.m[2][0] = 0;     T12.m[2][1] = 0;         T12.m[2][2] = 1;  T12.m[2][3] = 0;
    T12.m[3][3] = 1;

    // --------------------------------------------------
    // DH-матрица трансформации T23 (сустав 2 → сустав 3)
    // --------------------------------------------------
    // Сустав 3: вращение вокруг оси Z (угол q3)
    // DH-параметры: a[2]=155мм, alpha[2]=0°, d[3]=0мм
    //
    // Аналогично T12: оси Z2 и Z3 параллельны
    float c3 = cos(q3r), s3 = sin(q3r);
    float ca3 = cos(alpha[2] * DEG_TO_RAD);
    Mat4 T23;
    T23.m[0][0] = c3;    T23.m[0][1] = -s3*ca3;  T23.m[0][2] = 0;  T23.m[0][3] = a[2]*c3;
    T23.m[1][0] = s3;    T23.m[1][1] = c3*ca3;   T23.m[1][2] = 0;  T23.m[1][3] = a[2]*s3;
    T23.m[2][0] = 0;     T23.m[2][1] = 0;         T23.m[2][2] = 1;  T23.m[2][3] = 0;
    T23.m[3][3] = 1;

    // --------------------------------------------------
    // Вычисление T03 = T01 · T12 · T23
    // --------------------------------------------------
    // Результат описывает трансформацию от основания до 3-го сустава.
    // Используется ассоциативность: (T01 · T12) · T23
    Mat4 T03 = matMultiply(matMultiply(T01, T12), T23);

    // --------------------------------------------------
    // Извлечение матрицы поворота R03 (3×3 из T03)
    // --------------------------------------------------
    // R03 — верхняя левая 3×3 подматрица T03.
    // Она описывает ориентацию 3-го сустава относительно основания.
    Mat4 R03 = Mat4::identity();
    for (int i = 0; i < 3; i++)
        for (int j = 0; j < 3; j++)
            R03.m[i][j] = T03.m[i][j];

    // ================================================================
    // ШАГ 2: Вычисление R06 из целевой ориентации (Эйлер ZYX)
    // ================================================================
    // Желаемая ориентация конца инструмента задаётся углами Эйлера ZYX:
    //   roll (A), pitch (B), yaw (C)
    // Преобразуем их в матрицу поворота R06 с помощью eulerToMatrix().
    // R06 = Rz(yaw) · Ry(pitch) · Rx(roll)
    Mat4 R06 = eulerToMatrix(A * DEG_TO_RAD, B * DEG_TO_RAD, C * DEG_TO_RAD);

    // ================================================================
    // ШАГ 3: Вычисление матрицы запястья R36 = R03⁻¹ · R06
    // ================================================================
    // Из R06 = R03 · R36 следует R36 = R03⁻¹ · R06.
    // Поскольку R03 — ортогональная матрица (матрица поворота),
    // её обратная равна транспонированной: R03⁻¹ = R03ᵀ.
    //
    // Это ключевое уравнение: оно «вычитает» вклад первых трёх
    // суставов из общей ориентации, оставляя только вклад запястья.
    Mat4 R03T = matTranspose(R03);  // R03⁻¹ = R03ᵀ
    Mat4 R36 = matMultiply(R03T, R06);  // R36 = R03ᵀ · R06

    // ================================================================
    // ШАГ 4: Декомпозиция R36 на углы Эйлера ZYX (q4, q5, q6)
    // ================================================================
    // Матрица R36 описывает ориентацию запястья относительно 3-го сустава.
    // Декомпозируем её на три элементарных поворота:
    //   R36 = Rz(q5) · Ry(q4) · Rx(q6)
    // Где:
    //   q4 — pitch (тангаж, поворот вокруг Y)
    //   q5 — yaw (рыскание, поворот вокруг Z)
    //   q6 — roll (крен, поворот вокруг X)
    decomposeRotation(R36, q4, q5, q6);

    return true;
}

