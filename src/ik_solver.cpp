/**
 * Проверка достижимости целевой позиции.
 *
 * Вызывает solvePosition() для проверки, может ли манипулятор
 * достичь заданной точки (x, y, z). Ориентация не проверяется —
 * только позиция.
 *
 * Используется для предварительной проверки перед началом движения
 * или для определения границ рабочего пространства.
 *
 * @param target — целевая поза (проверяется только позиция)
 * @return true если точка находится в рабочем пространстве
 */
bool IKSolver::isReachable(const Pose &target) {
    float q1, q2, q3;
    // Решаем только задачу позиции (q1–q3).
    // Если solvePosition вернул true — точка достижима.
    return solvePosition(target.position.x, target.position.y, target.position.z,
                         q1, q2, q3);
}

