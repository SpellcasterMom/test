/**
 * @file config.h
 * @brief Конфигурация робота-манипулятора 6DOF
 *
 * Содержит все параметры hardware:
 * - Длины звеньев и DH-параметры
 * - Конфигурация сервоприводов
 * - Ограничения рабочей зоны
 * - Параметры безопасности
 * - Настройки движения
 *
 * =====================================================================
 * ВАЖНО (Last modify: 2026-09-25):
 * =====================================================================
 * В ServoConfig добавлено поле homeOffset — сдвиг между математическим
 * углом (q_math, из IK) и физическим углом сервы (servoAngle).
 *
 *   servoAngle = q_math + homeOffset
 *
 * Для P1–P3 (сервы 270°) homeOffset = 135° — при q_math = 0 серва стоит
 * в середине хода.
 * Для P4–P6 (сервы 180°) homeOffset =  90°.
 * Для P7 (gripper)  homeOffset =   0°.
 *
 * minAngle/maxAngle остаются в МАТЕМАТИЧЕСКОМ диапазоне
 * (-135..+135 для P1–P3, -90..+90 для P4–P6, 0..100 для P7) —
 * их использует safety. ServoController сам прибавляет homeOffset
 * перед конвертацией в PWM.
 */

#pragma once

#include <cstdint>

// ====================================================================
// Длины звеньев (мм)
// ====================================================================
// L0 = 110 мм — высота базы (от стола до плеча)
// L1 = 160 мм — плечо (плечо → локоть)
// L2 = 155 мм — предплечье (локоть → запястье)
// L3 = 25 мм  — переход запястья
// L4 = 25 мм  — ориентация запястья (pitch)
// L5 = 25 мм  — захват (yaw/roll)
const int LINK_LENGTHS[] = {110, 160, 155, 25, 25, 25};

// ====================================================================
// Параметры захвата
// ====================================================================
// Длина пальцев захвата от центра запястья до TCP (Tool Center Point)
// Используется для расчёта FK (кончик пальцев) и safety (виртуальная 7-я линия)
const float GRIPPER_FINGER_LENGTH = 0.0;  // мм

// ====================================================================
// DH-параметры (Denavit-Hartenberg)
// ====================================================================
// Формат: {a (мм), alpha (градусы), d (мм), theta_offset (градусы)}
//
// a     — расстояние вдоль оси X (длина звена)
// alpha — угол поворота вокруг оси X (наклон следующей оси)
// d     — расстояние вдоль оси Z (высота звена)
// theta — смещение угла поворота вокруг оси Z
//
// Матрица DH-преобразования:
// T = [ct   -st*ca    st*sa    a*ct ]
//     [st    ct*ca   -ct*sa    a*st ]
//     [0     sa       ca       d    ]
//     [0     0        0        1    ]
// где ct=cos(θ), st=sin(θ), ca=cos(α), sa=sin(α)
const float DH_PARAMS[6][4] = {
    {25,    90,  LINK_LENGTHS[0], 0},   // Joint 1: база (вращение вокруг Z)
    {160,    0,   0,               0},   // Joint 2: плечо (наклон)
    {155,    0,   0,               0},   // Joint 3: локоть (наклон)
    {25,    90,   0,               0},   // Joint 4: запястье pitch (наклон)
    {25,   -90,   0,               0},   // Joint 5: запястье roll (вращение)
    {25,     0,   0,               0},   // Joint 6: запястье yaw (поворот)
};

// ====================================================================
// Конфигурация сервопривода
// ====================================================================
// Описывает характеристики одного сервопривода:
// - Диапазон углов (math) и PWM
// - Корректировка и компенсация люфта
// - Инверсия направления вращения
// - Домашний сдвиг (math → servo)
struct ServoConfig {
    uint8_t  id;                          // ID сервопривода (0-6)
    int16_t  minAngle;                    // минимальный MATH-угол (градусы)
    int16_t  maxAngle;                    // максимальный MATH-угол (градусы)
    uint16_t minPWM;                      // минимальный PWM (мкс)
    uint16_t maxPWM;                      // максимальный PWM (мкс)
    uint16_t maxAngularSpeed;             // максимальная скорость (градусы/с)
    float    correctionFactor;            // корректировка (100.0 = без коррекции)
    int16_t  backlashCompensation;        // компенсация люфта (градусы)
    bool     isInverted;                  // инверсия направления вращения
    int16_t  homeOffset;                  // ← НОВОЕ: math→servo (135° / 90° / 0°)
    uint8_t  directionCorrection[2];      // корректировка [CW, CCW] (для будущего)
};

// ====================================================================
// Ограничения рабочей зоны (мм)
// ====================================================================
// Определяет прямоугольную область, в которой рука может работать:
// - X: ±250 мм от центра базы
// - Y: ±250 мм от центра базы
// - Z: от 20 мм (2 см от стола) до 400 мм
struct WorkspaceLimits {
    float xMin, xMax;  // границы по X
    float yMin, yMax;  // границы по Y
    float zMin, zMax;  // границы по Z (zMin = высота стола + запас)
};

const WorkspaceLimits WORKSPACE = {
    .xMin = -250, .xMax = 250,
    .yMin = -250, .yMax = 250,
    .zMin = 0,     .zMax = 400,    // Z min = 0 (уровень стола)
};

// ====================================================================
// Параметры безопасности звеньев (мм)
// ====================================================================
// Определяет ограничения для каждого звена робота:
// - zMin[i] — минимальная высота для звена i (защита от столкновения со столом)
// - maxReach — максимальный радиус вытягивания (415 мм макс - 2 см запас = 395 мм)
// - minReach — минимальный радиус (защита от слишком близкого расположения к оси)
struct LinkSafety {
    float zMin[6];      // минимальная Z для каждого из 6 звеньев
    float maxReach;     // максимальный радиус (мм)
    float minReach;     // минимальный радиус (мм)
};

const LinkSafety DEFAULT_LINK_SAFETY = {
    .zMin = {0, 0, 20, 20, 20, 20},       // база и плечо на уровне стола, локоть+ не ниже 2 см
    .maxReach = 395,                        // 415 мм макс - 2 см запас
    .minReach = 0,                          // минимальный радиус не ограничен
};

// ====================================================================
// Запретная зона
// ====================================================================
// Прямоугольная область, в которую рука НЕ ДОЛЖНА входить.
// Используется для защиты от столкновений с объектами на столе.
struct ForbiddenZone {
    float xMin, xMax;  // границы по X
    float yMin, yMax;  // границы по Y
    float zMin, zMax;  // границы по Z
    bool  active;      // активна ли зона
};

// Максимальное количество запретных зон
const int MAX_FORBIDDEN_ZONES = 10;

// ====================================================================
// Полная конфигурация манипулятора
// ====================================================================
// Содержит все настройки робота:
// - Конфигурации всех 7 сервоприводов
// - Ограничения рабочей зоны
// - Параметры безопасности
// - Запретные зоны
// - Длина пальцев захвата
struct ManipulatorConfig {
    ServoConfig    servos[7];                        // конфигурации сервоприводов
    WorkspaceLimits workspace;                       // ограничения рабочей зоны
    LinkSafety     linkSafety;                       // параметры безопасности звеньев
    ForbiddenZone  forbiddenZones[MAX_FORBIDDEN_ZONES]; // запретные зоны
    int            forbiddenZoneCount;               // количество активных запретных зон
    float          fingerLength;                     // длина пальцев захвата (мм)
};

// ====================================================================
// Конфигурация сервоприводов по умолчанию
// ====================================================================
// Параметры для каждого из 7 сервоприводов:
//   ID: 0-5 = суставы, 6 = захват
//   minAngle/maxAngle — MATH-диапазон (то, что видят FK/IK/safety)
//   homeOffset — сдвиг math → servo (135° для 270°-серв, 90° для 180°-серв)
//
//   При q_math = 0 физический угол сервы = homeOffset.
//   Для P1–P3 (270°): 0 → 135° (середина)
//   Для P4–P6 (180°): 0 →  90° (середина)
//   Для P7 (gripper): 0 →   0°
const ServoConfig DEFAULT_SERVO_CONFIG[7] = {
    // id, minA, maxA, minPWM, maxPWM, speed, correction, backlash, inverted, homeOffset, {CW, CCW}
    {0, -135, 135,  500, 2500, 30, 100, 2, false, 135, {0, 0}},   // Base         math 0 → servo 135
    {1, -135, 135,  500, 2500, 30, 100, 1, false, 135, {0, 0}},   // Shoulder     math 0 → servo 135
    {2, -135, 135,  500, 2500, 30, 100, 2, false, 135, {0, 0}},   // Elbow        math 0 → servo 135
    {3,  -90,  90,  500, 2500, 180, 100, 1, false,  90, {0, 0}},   // Wrist pitch  math 0 → servo  90
    {4,  -90,  90,  500, 2500, 180, 100, 1, false,  90, {0, 0}},   // Wrist roll   math 0 → servo  90
    {5,  -90,  90,  500, 2500, 180, 100, 1, false,  90, {0, 0}},   // Wrist yaw    math 0 → servo  90
    {6,    0, 100,  500, 2500,  90, 100, 0, false,   0, {0, 0}},   // Gripper      без offset
};

// ====================================================================
// Конфигурация по умолчанию
// ====================================================================
// Содержит все дефолтные параметры для первого запуска.
// После калибровки сохраняется в EEPROM (M500) и загружается при старте (M501).
const ManipulatorConfig DEFAULT_CONFIG = {
    .servos = {
        DEFAULT_SERVO_CONFIG[0],
        DEFAULT_SERVO_CONFIG[1],
        DEFAULT_SERVO_CONFIG[2],
        DEFAULT_SERVO_CONFIG[3],
        DEFAULT_SERVO_CONFIG[4],
        DEFAULT_SERVO_CONFIG[5],
        DEFAULT_SERVO_CONFIG[6],
    },
    .workspace = WORKSPACE,
    .linkSafety = DEFAULT_LINK_SAFETY,
    .forbiddenZones = {},
    .forbiddenZoneCount = 0,
    .fingerLength = GRIPPER_FINGER_LENGTH,
};

// ====================================================================
// Домашняя позиция (градусы)
// ====================================================================
// Углы сервоприводов для позиции "домой" по умолчанию.
// {0, 0, 0, 0, 0, 0, 50} = все суставы по центру, захват наполовину открыт.
// Сохраняется в EEPROM командой M111.
//
// ВАЖНО: углы здесь МАТЕМАТИЧЕСКИЕ (q_math), а не серво.
// При q_math = 0 серва встанет на homeOffset (135° для P1–P3, 90° для P4–P6).
const float DEFAULT_HOME_ANGLES[7] = {0, 0, 0, 0, 0, 0, 50};

// ====================================================================
// Параметры движения
// ====================================================================
// STEP_INTERVAL_MS — интервал между шагами интерполяции (мс).
//   Чем меньше → плавнее движение, но больше нагрузка на процессор.
//   Рекомендуется: 15-25 мс.
//
// MIN_STEP_DEG — минимальный шаг (градусы).
//   Если изменение угла меньше этого значения, движение не выполняется.
//   Защита от "дрожания" при очень малых перемещениях.
//
// DEFAULT_FEEDRATE — скорость перемещения по умолчанию (мм/с).
//   Используется если G-код не содержит параметр F.
const float STEP_INTERVAL_MS     = 20.0;   // интервал шага (мс)
const float MIN_STEP_DEG         = 0.1;    // минимальный шаг (градусы)
const float DEFAULT_FEEDRATE     = 500.0;  // скорость по умолчанию (мм/с)