#define SERIAL_BAUD 921600

// ====================================================================
// Длины звеньев (мм)
// ====================================================================
// L0 = 134 мм — высота базы (от стола до оси J2), чертёж robot1
// L1 = 165 мм — плечо (J2 → J3)
// L2 = 161 мм — предплечье (J3 → J4)
// L3 = 54 мм  — запястье, сегмент вдоль руки (J4 → J5)
// L4 = 53 мм  — запястье, боковой сдвиг (J5 → J6)
// L5 = 27 мм  — запястье, вылет фланца (J6 → фланец)
const int LINK_LENGTHS[] = {134, 165, 161, 54, 53, 27};

// ====================================================================
// Параметры захвата
// ====================================================================
// Кинематическая длина пальца: от фланца O6 (сустав 6 = фланец (27,53,514)
// в нулях) до TCP. Ровно длина захвата по чертежу robot1: 105 мм.
// (Ось J6 идёт вдоль инструмента, поэтому J6→фланец 27 мм сидит в DH
// как d звена 6, а не в пальце.) Команда G0 задаёт TCP (кончик захвата).
const float GRIPPER_FINGER_LENGTH = 105.0;  // мм

// ====================================================================
// DH-параметры (Denavit-Hartenberg)
// ====================================================================
// Формат: {a (мм), alpha (градусы), d (мм), theta_offset (градусы)}
//
// a     — расстояние вдоль оси X (длина звена)
// alpha — угол поворота вокруг оси X (наклон следующей оси)
// d     — расстояние вдоль оси Z (высота звена)
// theta — смещение угла поворота вокруг оси Z
//
// Матрица DH-преобразования:
// T = [ct   -st*ca    st*sa    a*ct ]
//     [st    ct*ca   -ct*sa    a*st ]
//     [0     sa       ca       d    ]
//     [0     0        0        1    ]
// где ct=cos(θ), st=sin(θ), ca=cos(α), sa=sin(α)
// Выведены из чертежа robot1 + физика железа (нулевая поза = вертикальная рука):
//   J2=(0,0,134) J3=(0,0,299) J4=(0,0,460) J5=(0,0,514) J6=(0,53,514)
//   фланец=(27,53,514) TCP=(132,53,514) инструмент=+X.
// Оси нулей: J1=Z, J2=J3=J4=-Y, J5=+Z, J6=+X (J6 = roll вокруг инструмента!).
// J4/J5 пересекаются в J4 (a=0); 54 мм сидит в d звена 5; 27 мм — в d звена 6.
// v2: J6 вдоль инструмента (железо: P6 крутит захват вокруг его оси,
// v1 ошибочно клала J6 вертикально — TCP описывал дугу). FK нулей точен,
// P6=±любой: TCP стоит (132,53,514).
// NOTE: знаки q5/q6 и инверсии серв P5–P6 проверить на железе (jog ±10°).
const float DH_PARAMS[6][4] = {
    {0,     90,  134,  0},    // Joint 1: база (вращение вокруг Z)
    {165,    0,    0,  90},   // Joint 2: плечо (наклон), ноль = ВЕРТИКАЛЬ
    {161,    0,    0,   0},   // Joint 3: локоть (наклон)
    {0,    -90,    0, -90},   // Joint 4: запястье pitch (оси J4/J5 пересекаются)
    {53,    90,   54,  90},   // Joint 5: запястье (J5 → J6 = 53 мм, +54 вдоль Z)
    {0,      0,   27,   0},   // Joint 6: roll фланца (J6 → фланец = 27 мм вдоль +X)
};
// NOTE: theta_offset J2 = +90°: математический ноль плеча — вертикаль вверх
// (железо: серва 270° в середине 135° = рука вверх). Без этого ноль модели
// (горизонт, вылет 415мм) не совпадал с нулём железа.

// ====================================================================
// Конфигурация сервопривода
// ====================================================================
// Описывает характеристики одного сервопривода:
// - Диапазон углов (math) и PWM
// - Корректировка и компенсация люфта
// - Инверсия направления вращения
// - Домашний сдвиг (math → servo)
struct ServoConfig {
    uint8_t  id;                          // ID сервопривода (0-6)
    int16_t  minAngle;                    // минимальный MATH-угол (градусы)
    int16_t  maxAngle;                    // максимальный MATH-угол (градусы)
    uint16_t minPWM;                      // минимальный PWM (мкс)
    uint16_t maxPWM;                      // максимальный PWM (мкс)
    uint16_t maxAngularSpeed;             // максимальная скорость (градусы/с)
    float    correctionFactor;            // корректировка (100.0 = без коррекции)
    int16_t  backlashCompensation;        // компенсация люфта (градусы)
    bool     isInverted;                  // инверсия направления вращения
    int16_t  homeOffset;                  // ← НОВОЕ: math→servo (135° / 90° / 0°)
    uint8_t  directionCorrection[2];      // корректировка [CW, CCW] (для будущего)
};

// ====================================================================
// Ограничения рабочей зоны (мм)
// ====================================================================
// Определяет прямоугольную область, в которой рука может работать:
// - X: ±250 мм от центра базы
// - Y: ±250 мм от центра базы
// - Z: от 20 мм (2 см от стола) до 400 мм
struct WorkspaceLimits {
    float xMin, xMax;  // границы по X
    float yMin, yMax;  // границы по Y
    float zMin, zMax;  // границы по Z (zMin = высота стола + запас)
};

const WorkspaceLimits WORKSPACE = {
    .xMin = -560, .xMax = 560,
    .yMin = -560, .yMax = 560,
    .zMin = 0,     .zMax = 700,    // Z min = 0 (уровень стола)
};
// Прямоугольник = истинные габариты по чертежу robot1 (двойник, 4000 сэмплов):
// maxR_xy=539, max|X/Y|=525, maxZ=667. Старый 250/400 жал под неверную геометрию
// и браковал даже нули (TCP z=514).

// ====================================================================
// Параметры безопасности звеньев (мм)
// ====================================================================
// Определяет ограничения для каждого звена робота:
// - zMin[i] — минимальная высота для звена i (защита от столкновения со столом)
// - maxReach — максимальный радиус вытягивания (415 мм макс - 2 см запас = 395 мм)
// - minReach — минимальный радиус (защита от слишком близкого расположения к оси)
struct LinkSafety {
    float zMin[6];      // минимальная Z для каждого из 6 звеньев
    float maxReach;     // максимальный радиус (мм)
    float minReach;     // минимальный радиус (мм)
};

const LinkSafety DEFAULT_LINK_SAFETY = {
    .zMin = {0, 0, 10, 10, 10, 10},       // база и плечо на уровне стола; остальным 10 мм над столом (было 20 — браковало рабочие позы: Link 2 на 17.3 мм)
    .maxReach = 560,                        // истинный вылет ~539 + запас
    .minReach = 0,                          // минимальный радиус не ограничен
};

// ====================================================================
// Запретная зона
// ====================================================================
// Прямоугольная область, в которую рука НЕ ДОЛЖНА входить.
// Используется для защиты от столкновений с объектами на столе.
struct ForbiddenZone {
    float xMin, xMax;  // границы по X
    float yMin, yMax;  // границы по Y
    float zMin, zMax;  // границы по Z
    bool  active;      // активна ли зона
    uint8_t skipLinks; // битмаска звеньев, НЕ проверяемых на эту зону
                       // (бит i = звено i не проверяется: статика/конструктив
                       // живёт внутри по построению, проверять бессмысленно)
};

// Максимальное количество запретных зон
const int MAX_FORBIDDEN_ZONES = 10;

// Конструктив: колонна базы как запретная зона по умолчанию.
// Параллелепипед X/Y ±65 (квадрат 130, центр в 0), Z 0..180,
// грани по координатным плоскостям. Рука не должна входить в железо.
// Проверяется на старте: если такой зоны нет — добавляется и сохраняется.
// Маска: звенья 0,1,2 не проверяются (идея: статика и начало локтя живут
// внутри по построению — считать их столкновение со столом бессмысленно).
const ForbiddenZone DEFAULT_CONSTRUCT_ZONE = {-65, 65, -65, 65, 0, 180, true, 0x07};

// ====================================================================
// Полная конфигурация манипулятора
// ====================================================================
